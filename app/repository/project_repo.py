def create_project(
    db: Session,
    *,
    user_id: UUID,
    title: str,
) -> Project:
    """
    Create a project and its default Style Book atomically.

    The Style Book is created immediately with default values,
    so a newly created project never starts without a Style Book.

    The transaction is committed only after both records have
    been added successfully.
    """

    project = Project(
        user_id=user_id,
        title=title,
    )

    db.add(project)

    # The project ID is generated by SQLAlchemy.
    # Flush makes it available before the transaction is committed.
    db.flush()

    default_style_book = StyleBook(
        project_id=project.id,
        content=_get_default_style_book_content(),
    )
    db.add(default_style_book)

    # Atomically create initial conversation and welcome message
    default_conversation = Conversation(
        project_id=project.id,
        title="Creative Idea",
        stage="idea",
    )
    db.add(default_conversation)
    db.flush()

    welcome_msg = Message(
        conversation_id=default_conversation.id,
        role="assistant",
        content="Welcome to our AI video studio! I'm excited to collaborate with you on your video project. Can you please share a bit about your idea or story premise to get us started?",
        message_metadata={"action": "ask_question"},
    )
    db.add(welcome_msg)

    # Commit project + default Style Book + conversation + welcome message together.
    db.commit()

    db.refresh(project)

    return project


def get_projects_by_user(
    db: Session,
    *,
    user_id: UUID,
    offset: int,
    limit: int,
) -> tuple[list[Project], int]:
    """Return paginated projects for a user."""

    total = (
        db.scalar(
            select(func.count())
            .select_from(Project)
            .where(Project.user_id == user_id)
        )
        or 0
    )

    statement = (
        select(Project)
        .where(Project.user_id == user_id)
        .order_by(Project.created_at.desc())
        .offset(offset)
        .limit(limit)
    )

    projects = list(db.scalars(statement).all())

    return projects, total


def get_project_by_id(
    db: Session,
    *,
    project_id: UUID,
    user_id: UUID,
) -> Project | None:
    """Return a project owned by the authenticated user."""

    statement = (
        select(Project)
        .where(
            Project.id == project_id,
            Project.user_id == user_id,
        )
    )

    return db.scalar(statement)


def update_project(
    db: Session,
    *,
    project: Project,
    title: str,
) -> Project:
    """Update a project."""

    project.title = title

    db.commit()
    db.refresh(project)

    return project


def delete_project(
    db: Session,
    *,
    project: Project,
) -> None:
    """Delete a project."""

    db.delete(project)
    db.commit()